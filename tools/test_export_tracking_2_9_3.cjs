// Private source stays outside the repository. Pass the supplied 17-message export locally.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { runtime } = require('./test_panel_tracking.cjs');
assert(process.argv[2], 'Pass the supplied 17-message reference export');
const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const r = runtime(), c = r.ctx;
const chat = data.messages.map(m => ({ ...m, role: m.is_user ? 'user' : 'assistant', metadata: m.extra?.spindle_metadata || {} }));
const before = JSON.stringify(chat);
const last = c.getSwipeData(chat.at(-1));
assert.equal(last.survival.study[0].note.length, 80, 'Reference changed: re-audit truncation');
assert.equal(last.survival.spells.length, 1);
c.setLorePool('export-review', [{ id: 'orb', key: ['Water Ball', 'Waterball'], content: '[SPELL — Water Ball]\nSchool: Water · Rank: Beginner\nEffect: A water sphere.' }]);
const st = c.emptyChatState();
const known = c.spellKnown(chat, st, null, 'export-review');
assert.equal(known.size, 1); assert(known.has('water ball'));
assert.equal(c.spellStudyActive(chat, st, null, 'export-review').length, 0);
const magic = c.spellListPanel('export-review', chat, st, c.hmsReadSystems(c.parseHud(chat.at(-1).content)));
assert.equal(magic.studying.length, 0);
assert.equal(magic.schools.flatMap(s => s.spells).find(s => s.name === 'Water Ball').status, 'known');
const agenda = c.agendaRead(chat, {}).items;
const scheduled = agenda.find(x => /measurement/i.test(x.what));
assert(scheduled); assert.equal(scheduled.state, 'open');
assert.equal(scheduled.dueAt % 1440, 510, 'Confirmed appointment time changed');
const gear = c.gearRead(chat, {}).items;
assert(!gear.some(x => /^permission to borrow/i.test(x.name)));
assert(gear.some(x => /primer/i.test(x.name)), 'Actual transferred physical books disappeared');
assert.equal(JSON.stringify(chat), before, 'Read rewrote saved metadata');
console.log('17-message export replay passed: future measurement stays open, permission is not gear, actual books remain, casting-method spell aliases are Known with no automatic study entry, saved metadata is unchanged.');
console.log('The historical 80-character note is already truncated and cannot be reconstructed from its stored row. A normal manual Refresh can regenerate that report; no automatic extra generation is added.');
